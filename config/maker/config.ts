export const ALLOWED_VIDEO_FORMATS = ['video/webm', 'video/mp4', 'video/quicktime'];
export const ALLOWED_AUDIO_FORMATS = ['audio/mp3', 'audio/wav', 'audio/m4a', 'audio/aac'];

export function getReadableVideoFormats() {
  const readableFormats = ALLOWED_VIDEO_FORMATS.map((mimeType) => {
    switch (mimeType) {
      case 'video/webm':
        return 'WebM';
      case 'video/mp4':
        return 'MP4';
      case 'video/quicktime':
          return 'MOV';
      default:
        return 'Unknown';
    }
  });

  return readableFormats.join(', ');
}

export function getReadableAudioFormats() {
  const readableFormats = ALLOWED_AUDIO_FORMATS.map((mimeType) => {
    switch (mimeType) {
      case 'audio/mp3':
        return 'MP3';
      case 'audio/wav':
        return 'WAV';
      case 'audio/m4a':
        return 'M4A';
      case 'audio/aac':
        return 'AAC';
      default:
        return 'Unknown';
    }
  });

  return readableFormats.join(', ');
}